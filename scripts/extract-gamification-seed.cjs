/**
 * One-off extractor: copies challenge + achievement arrays from frontend mockData.ts
 * into backend CommonJS seed data (no TS runtime required).
 * Run: node scripts/extract-gamification-seed.cjs
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const mockPath = path.join(root, "..", "frontend", "src", "data", "mockData.ts");
const outPath = path.join(root, "src", "seeders", "gamificationSeedData.js");

const text = fs.readFileSync(mockPath, "utf8");

function extractConstArray(name) {
  const re = new RegExp(`export const ${name}\\b[^=]*=\\s*`);
  const m = text.match(re);
  if (!m) throw new Error(`Missing export const ${name}`);
  // Skip TypeScript `Challenge[]` — find first `= [` (array literal)
  const eq = text.indexOf("=", m.index);
  const start = text.indexOf("[", eq);
  if (start === -1 || start > eq + 20) {
    const start2 = text.indexOf("=[", eq);
    if (start2 === -1) throw new Error(`No array literal for ${name}`);
    return extractFromBracket(text, start2 + 1);
  }
  return extractFromBracket(text, start);
}

function extractFromBracket(text, start) {
  let depth = 0;
  let i = start;
  for (; i < text.length; i++) {
    const c = text[i];
    if (c === "[") depth++;
    else if (c === "]") {
      depth--;
      if (depth === 0) {
        i++;
        break;
      }
    }
  }
  return text.slice(start, i);
}

const challengesLiteral = extractConstArray("challenges");
const achievementsLiteral = extractConstArray("achievements");

const out = `/* AUTO-GENERATED by scripts/extract-gamification-seed.cjs — do not edit by hand */
/* Source: frontend/src/data/mockData.ts */

exports.challenges = ${challengesLiteral};

exports.achievements = ${achievementsLiteral};
`;

fs.writeFileSync(outPath, out, "utf8");
console.log("Wrote", outPath);
